// Builds supabase/master.sql: every migration in order, 10 blank lines apart, then the schema check.
// Paste the whole file into the Supabase SQL editor and run it; run it again after each new migration.
//
// Each migration runs once: public.schema_migrations records what has been applied and the
// migration body is skipped when it is already there. Databases set up before this ledger existed
// (12 Nov 2026) had 0001 to 0014 applied by hand; the baseline marks those as done on first run.
// 0015 onward are written to be re-runnable, so running them again on such a database is safe.
//
// After adding a migration to supabase/migrations: npm run sql:master
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const BASELINE_LAST = "0014";
const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const gap = "\n".repeat(10);
const name = (f) => f.replace(/\.sql$/, "");

const head = `-- Anargya Corp: all migrations in one file (${files[0]} to ${files.at(-1)}).
-- Generated by scripts/build-master-sql.mjs. Do not edit by hand: change or add a migration in
-- supabase/migrations, then run npm run sql:master. Paste everything and run; already applied
-- migrations are skipped. The last query lists missing columns/functions: 0 rows means complete.

create table if not exists public.schema_migrations (name text primary key, applied_at timestamptz not null default now());
alter table public.schema_migrations enable row level security; -- no policies: SQL editor / service role only

-- Baseline for databases created before this ledger: ${files[0]} to ${BASELINE_LAST} were applied by hand.
insert into public.schema_migrations (name)
select unnest(array[${files.filter((f) => f.slice(0, 4) <= BASELINE_LAST).map((f) => `'${name(f)}'`).join(", ")}])
where to_regclass('public.products') is not null
  and not exists (select 1 from public.schema_migrations)
on conflict do nothing;`;

const parts = files.map((f) => {
  const n = name(f), tag = f.slice(0, 4);
  const body = readFileSync(new URL(f, dir), "utf8").trim();
  return `-- ============ ${f} ============
do $mig_${tag}$
begin
  if exists (select 1 from public.schema_migrations where name = '${n}') then return; end if;
  execute $body_${tag}$
${body}
$body_${tag}$;
  insert into public.schema_migrations (name) values ('${n}');
end
$mig_${tag}$;`;
});

const check = readFileSync(new URL("../supabase/maintenance/check_schema.sql", import.meta.url), "utf8").trim();
writeFileSync(
  new URL("../supabase/master.sql", import.meta.url),
  `${head}${gap}${parts.join(gap)}${gap}-- ============ check (maintenance/check_schema.sql) ============\n${check}\n`,
);
console.log(`supabase/master.sql: ${files.length} migrations, baseline up to ${BASELINE_LAST}`);
